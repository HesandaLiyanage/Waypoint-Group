import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import ts from 'typescript';
const source=readFileSync(new URL('../src/shells/dispatcher/model.ts',import.meta.url),'utf8');
const compiled=ts.transpileModule(source,{compilerOptions:{target:ts.ScriptTarget.ES2022,module:ts.ModuleKind.ES2022}}).outputText;
const {initialState,reducer,canConfirm,canRecord,planWarnings,trips,compatibility,deferred,validNextDate}=await import(`data:text/javascript;base64,${Buffer.from(compiled).toString('base64')}`);
let state=initialState();
assert.equal(reducer(state,{type:'generate'}),state);
state=reducer(state,{type:'close'});
assert.equal(reducer(state,{type:'priority',id:state.orders[0].id}),state);
state=reducer(state,{type:'generate'});
assert.equal(planWarnings(state).length,0,'generated proposals satisfy modelled constraints');
assert.ok(deferred(state).length>0,'real sample shortages remain');
assert.ok(deferred(state).every(o=>o.proposal&&o.reason&&!o.reviewed),'explanations prefilled; decisions not accepted automatically');
const served=state.orders.find(o=>o.trip),oldTrip=served.trip;
assert.equal(reducer(state,{type:'defer',id:served.id,reason:'Fleet capacity',nextDate:'2026-10-11',note:'Make room for an urgent order.'}),state,'Sunday not an operating day');
assert.equal(validNextDate('2026-10-32'),false);
assert.equal(validNextDate('2026-10-05'),false);
state=reducer(state,{type:'defer',id:served.id,reason:'Prioritise another outlet',nextDate:'2026-10-06',note:'Make room for an urgent outlet.'});
assert.equal(state.orders.find(o=>o.id===served.id).trip,null,'dispatcher can remove an assigned order');
state=reducer(state,{type:'reassign',id:served.id,trip:oldTrip});
assert.equal(state.orders.find(o=>o.id===served.id).trip,oldTrip,'dispatcher can restore a proposed deferral');
const ambient={...served,temp:'Ambient',vanOnly:false,district:'Colombo'};
assert.equal(compatibility(ambient,trips[0],[]).includes('Refrigeration required'),false,'reefer can carry ambient');
assert.ok(compatibility({...ambient,temp:'Chilled'},trips[3],[]).includes('Refrigeration required'));
assert.ok(compatibility({...served,vanOnly:true},trips[0],[]).includes('Van-only access'));
assert.ok(compatibility({...served,kg:99999},trips[0],[]).includes('Weight capacity exceeded'));
assert.equal(canRecord(state),false,'planner suggestions require acceptance');
for(const o of deferred(state))state=reducer(state,{type:'review',id:o.id,note:'No feasible trip after reviewing available capacity.',accepted:true});
assert.equal(canRecord(state),true);
state=reducer(state,{type:'record'});assert.equal(canConfirm(state),true);
state=reducer(state,{type:'confirm'});assert.equal(state.confirmed,true);
assert.equal(reducer(state,{type:'defer',id:served.id,reason:'Fleet capacity',nextDate:'2026-10-06',note:'Should remain locked.'}),state);
assert.equal(reducer(state,{type:'resolve',note:'Instructions sent to driver.',confirmed:true}),state,'instructions alone cannot resolve an incident');
state=reducer(state,{type:'ack'});assert.equal(state.issueStatus,'acknowledged');
assert.equal(reducer(state,{type:'instruct',instruction:{action:'wait',note:'Await safe unloading point.',reviewTime:'08:15'},coordinated:true}),state,'no waiting beyond Fresh cutoff');
state=reducer(state,{type:'instruct',instruction:{action:'alternate',note:'Store approved side bay; driver confirmed safe chilled unloading.',reviewTime:'06:25'},coordinated:true});
assert.equal(state.issueResolved,false);assert.equal(state.issueStatus,'awaiting');
assert.equal(reducer(state,{type:'resolve',note:'Side bay cleared and accepted.',confirmed:false}),state);
state=reducer(state,{type:'resolve',note:'Driver and store confirmed access restored.',confirmed:true});assert.equal(state.issueResolved,true);
const snapshot=state.orders;
state=reducer(state,{type:'capacity',depot:'Peliyagoda',agreed:true,plan:{shift:40,reefer:30,ambient:20,note:'Review spare second trips with depot operations.'}});
assert.equal(state.capacityPlans.Peliyagoda.reefer,30);assert.equal(state.orders,snapshot,'capacity requests do not silently modify orders');
assert.deepEqual(reducer(state,{type:'reset'}),initialState());
console.log('Dispatcher checks passed: explained proposals, manual defer/restore, constraints, review, operating dates, incident lifecycle, capacity proposals and reset.');
